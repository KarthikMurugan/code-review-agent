from .models import Report


def markdown(report: Report) -> str:
    lines = ["# Code review", "", f"Mode: **{report.mode}** · Status: **{report.status}**",
             f"Base: `{report.base_sha}`", f"Head: `{report.head_sha}`", ""]
    if report.mode == "demo":
        lines.extend(["> Scripted demonstration. These findings were not generated by a model.", ""])
    lines.extend(["## Specialist outcomes", ""])
    for result in sorted(report.agents, key=lambda r: r.role):
        lines.append(f"- {result.role}: {result.status}" +
                     (f" ({result.error})" if result.error else ""))
    lines.extend(["", "## Findings", ""])
    if not report.findings:
        lines.append("No findings were accepted. This is not a guarantee that the change is safe.")
    for item in report.findings:
        f = item.finding
        lines.extend([
            f"### {f.severity.upper()} · {item.role} · {f.title}", "",
            f"`{f.path}:{f.start_line}-{f.end_line}` · Confidence: {f.confidence}", "",
            f.explanation, "", f"**Trigger:** {f.trigger}", "",
            "**Evidence:**", "",
            *[f"> {line}" for line in f.evidence.splitlines()], "",
            f"**Suggested fix:** {f.suggested_fix}", "",
            f"**Suggested test:** {f.suggested_test}", "",
        ])
    lines.extend(["", "## Scope and limitations", ""])
    lines.extend(f"- {note}" for note in report.limitations)
    return "\n".join(lines) + "\n"
